static wgr_mesh_t *resolve_mesh(wgr_handle_t handle)
{
    uint16_t index = 0;
    if (!wgr_handle_pool_resolve(&wgr_mesh_pool, handle, &index)) {
        if (handle != 0) log_warn("Invalid mesh handle (%u)", (unsigned int)handle);
        return NULL;
    }
    return &wgr_meshes[index];
}

static wgr_model_t *resolve(wgr_handle_t handle)
{
    uint16_t index = 0;
    if (!wgr_handle_pool_resolve(&wgr_model_pool, handle, &index)) {
        if (handle != 0) log_warn("Invalid model handle (%u)", (unsigned int)handle);
        return NULL;
    }
    return &wgr_models[index];
}

/* A mesh's CPU data (any thread, for meshes that were never uploaded). */
static void free_mesh_cpu_data(wgr_mesh_t *mesh)
{
    for (int p = 0; p < mesh->prim_count; p++) {
        free(mesh->prims[p].pick_positions);
        free(mesh->prims[p].pick_indices);
        free(mesh->prims[p].pick_joints);
        free(mesh->prims[p].pick_weights);
        free(mesh->prims[p].pick_uvs[0]);
        free(mesh->prims[p].pick_uvs[1]);
        free(mesh->prims[p].pick_alpha);
        free(mesh->prims[p].upload_vertices);
    }
    free(mesh->prims);
    free_mesh_cpu(mesh);
}

static void free_mesh_data(wgr_mesh_t *mesh)
{
    for (int p = 0; p < mesh->prim_count; p++) {
        sg_destroy_buffer(mesh->prims[p].vbuf);
        sg_destroy_buffer(mesh->prims[p].ibuf);
        free(mesh->prims[p].pick_positions);
        free(mesh->prims[p].pick_indices);
        free(mesh->prims[p].pick_joints);
        free(mesh->prims[p].pick_weights);
        free(mesh->prims[p].pick_uvs[0]);
        free(mesh->prims[p].pick_uvs[1]);
        free(mesh->prims[p].pick_alpha);
        free(mesh->prims[p].upload_vertices);
    }
    free(mesh->prims);
    for (int m = 0; m < mesh->material_count; m++) {
        wgr_material_release(mesh->materials[m]);
    }
    free(mesh->materials);
    free_mesh_cpu(mesh);
}

static void retain_mesh(wgr_handle_t mesh_handle)
{
    wgr_mesh_t *mesh_ptr = resolve_mesh(mesh_handle);
    if (mesh_ptr != NULL) mesh_ptr->ref_count++;
}

static void release_mesh(wgr_handle_t mesh_handle)
{
    wgr_mesh_t *mesh_ptr = resolve_mesh(mesh_handle);
    if (mesh_ptr == NULL) return;
    if (mesh_ptr->ref_count > 0) mesh_ptr->ref_count--;
    if (mesh_ptr->ref_count == 0) {
        free_mesh_data(mesh_ptr);
        memset(mesh_ptr, 0, sizeof(*mesh_ptr));
        wgr_handle_pool_free(&wgr_mesh_pool, mesh_handle);
    }
}

static wgr_handle_t find_mesh_by_key(const char *path, bool generated)
{
    if (path == NULL || path[0] == '\0') return 0;
    for (uint16_t i = 1; i < wgr_mesh_pool.capacity; i++) {
        if (wgr_mesh_pool.occupied[i] && wgr_meshes[i].has_path && wgr_meshes[i].generated == generated &&
            strcmp(wgr_meshes[i].path, path) == 0) {
            return wgr_handle_pool_handle_from_index(&wgr_mesh_pool, i);
        }
    }
    return 0;
}

static wgr_handle_t find_mesh_by_path(const char *path)
{
    return find_mesh_by_key(path, false);
}

/* ------------------------------------------------------------ mesh loader */

/* A glTF file loaded into CPU data (prepare, any thread), created on the main
 * thread in steps: buffers, then one texture per step, then materials. */
typedef struct {
    wgr_mesh_t mesh;              /* moves into the mesh pool when finished */
    unsigned char *file;         /* the file's bytes: a .glb's buffers point into them */
    cgltf_data *gltf;
    wgr_gltf_textures_t textures;
    int step;                    /* 0 = buffers, then images, then materials */
    size_t next_image;
} wgr_mesh_prepared_t;

static void *prepare_mesh(const char *path)
{
    wgr_mesh_prepared_t *prepared;
    unsigned char *bytes;
    int size = 0;
    bool ok;

    bytes = read_file_bytes(path, &size);
    if (bytes == NULL) {
        log_error("failed to open model: %s", path != NULL ? path : "(null)");
        return NULL;
    }
    prepared = (wgr_mesh_prepared_t *)calloc(1, sizeof(wgr_mesh_prepared_t));
    ok = prepared != NULL && parse_model(&prepared->mesh, bytes, size, path, &prepared->gltf);
    if (!ok) {
        log_error("failed to load model: %s", path != NULL ? path : "(null)");
        if (prepared != NULL) free_mesh_cpu_data(&prepared->mesh);
        free(prepared);
        free(bytes);
        return NULL;
    }
    prepared->file = bytes;
    prepared->textures.gltf = prepared->gltf;
    prepared->textures.path = path; /* only while preparing: the loader's path outlives it */
    prepared->textures.images =
        (wgr_gltf_image_t *)calloc(prepared->gltf->images_count + 1, sizeof(wgr_gltf_image_t));
    if (prepared->textures.images != NULL) {
        /* images that textures use, decoded here (the slow part of most models) */
        for (cgltf_size t = 0; t < prepared->gltf->textures_count; t++) {
            const cgltf_texture *texture = &prepared->gltf->textures[t];
            const cgltf_image *compressed = ktx_image(prepared->gltf, texture);
            char uri[256];
            if (compressed != NULL && ktx_variant(compressed, uri, sizeof(uri)) &&
                read_ktx(&prepared->textures, compressed, uri)) {
                continue; /* uploaded as it is: no decoding */
            }
            if (texture->image != NULL) {
                decode_image(&prepared->textures, texture->image);
            }
        }
    }
    prepared->textures.path = NULL;
    return prepared;
}

static void discard_mesh(void *data)
{
    wgr_mesh_prepared_t *prepared = (wgr_mesh_prepared_t *)data;

    if (prepared == NULL) return;
    if (prepared->textures.images != NULL) {
        for (cgltf_size i = 0; i < prepared->gltf->images_count; i++) {
            wgr_texture_pixels_free(prepared->textures.images[i].pixels);
            free(prepared->textures.images[i].ktx_bytes);
            wgr_texture_release(prepared->textures.images[i].texture); /* materials hold what they use */
        }
    }
    free(prepared->textures.images);
    free_mesh_data(&prepared->mesh); /* empty once moved into the pool */
    cgltf_free(prepared->gltf);
    free(prepared->file);
    free(prepared);
}

/* The model shaders and pipelines, made when the first mesh reaches the GPU (or a
 * model is drawn) rather than at startup: a program without models doesn't compile
 * them (tools/webstart.mjs measures startup). */
static bool wgr_model_pipelines_ready;

/* A pipeline drawing model primitives with `shader` (built-in or custom: the vertex
 * layout is libwgrender's either way; shaders/wgr.glsl pins the same attribute locations). */
static sg_pipeline make_pipeline(sg_shader shader, bool skinned, bool blended, bool double_sided)
{
    sg_pipeline_desc d = {
        .shader = shader,
        .index_type = SG_INDEXTYPE_UINT32,
        .face_winding = SG_FACEWINDING_CCW,
        .depth = {.compare = SG_COMPAREFUNC_LESS_EQUAL, .write_enabled = !blended},
        .cull_mode = double_sided ? SG_CULLMODE_NONE : SG_CULLMODE_BACK,
        .label = "wgr-model-pip",
    };
    d.layout.attrs[0].format = SG_VERTEXFORMAT_FLOAT3;
    d.layout.attrs[1].format = SG_VERTEXFORMAT_FLOAT3;
    d.layout.attrs[2].format = SG_VERTEXFORMAT_FLOAT2; /* texcoord0 */
    d.layout.attrs[3].format = SG_VERTEXFORMAT_FLOAT2; /* texcoord1 */
    d.layout.attrs[4].format = SG_VERTEXFORMAT_FLOAT4; /* tangent */
    d.layout.attrs[5].format = SG_VERTEXFORMAT_FLOAT4; /* color0 */
    if (skinned) {
        d.layout.attrs[6].format = SG_VERTEXFORMAT_FLOAT4; /* joints */
        d.layout.attrs[7].format = SG_VERTEXFORMAT_FLOAT4; /* weights */
    }
    if (blended) {
        d.colors[0].blend = (sg_blend_state){
            .enabled = true,
            .src_factor_rgb = SG_BLENDFACTOR_SRC_ALPHA,
            .dst_factor_rgb = SG_BLENDFACTOR_ONE_MINUS_SRC_ALPHA,
            .src_factor_alpha = SG_BLENDFACTOR_ONE,
            .dst_factor_alpha = SG_BLENDFACTOR_ONE_MINUS_SRC_ALPHA,
        };
    }
    return sg_make_pipeline(&d);
}

static void ensure_pipelines(void)
{
    if (wgr_model_pipelines_ready) return;
    wgr_model_pipelines_ready = true;
    wgr_shd_static = make_static_shader();
    wgr_shd_skinned = make_skinned_shader();
    for (int skinned = 0; skinned < 2; skinned++) {
        for (int blended = 0; blended < 2; blended++) {
            for (int double_sided = 0; double_sided < 2; double_sided++) {
                wgr_pips[skinned][blended][double_sided] =
                    make_pipeline(skinned ? wgr_shd_skinned : wgr_shd_static, skinned, blended, double_sided);
            }
        }
    }
}

static bool upload_primitive(wgr_primitive_t *prim)
{
    ensure_pipelines();
    prim->vbuf = sg_make_buffer(&(sg_buffer_desc){
        .usage.vertex_buffer = true,
        .data = {.ptr = prim->upload_vertices, .size = prim->upload_bytes}});
    prim->ibuf = sg_make_buffer(&(sg_buffer_desc){
        .usage.index_buffer = true,
        .data = {.ptr = prim->pick_indices, .size = (size_t)prim->index_count * sizeof(uint32_t)}});
    free(prim->upload_vertices);
    prim->upload_vertices = NULL;
    if (sg_query_buffer_state(prim->vbuf) != SG_RESOURCESTATE_VALID ||
        sg_query_buffer_state(prim->ibuf) != SG_RESOURCESTATE_VALID) {
        log_error("model: couldn't create GPU buffers (see the sokol error above)");
        return false;
    }
    return true;
}

static wgr_loader_step_t finish_mesh(void *data, const char *path, wgr_handle_t *resource)
{
    wgr_mesh_prepared_t *prepared = (wgr_mesh_prepared_t *)data;
    wgr_mesh_t *mesh = &prepared->mesh;
    uint16_t index = 0;

    *resource = 0;
    if (prepared->step == 0) {
        for (int p = 0; p < mesh->prim_count; p++) {
            if (!upload_primitive(&mesh->prims[p])) {
                return WGR_LOADER_FAILED;
            }
        }
        prepared->step = 1;
        return WGR_LOADER_MORE;
    }
    if (prepared->textures.images != NULL) {
        while (prepared->next_image < prepared->gltf->images_count) {
            wgr_gltf_image_t *image = &prepared->textures.images[prepared->next_image++];
            if (image->ktx_bytes != NULL) {
                image->texture = wgr_texture_create_ktx(&image->ktx);
                image->failed = image->texture == 0;
                free(image->ktx_bytes);
                image->ktx_bytes = NULL;
                return WGR_LOADER_MORE;
            }
            if (image->pixels != NULL) {
                image->texture = wgr_texture_create_pixels(image->pixels, NULL, true);
                image->failed = image->texture == 0;
                wgr_texture_pixels_free(image->pixels);
                image->pixels = NULL;
                return WGR_LOADER_MORE;
            }
        }
    }

    prepared->textures.path = path;
    load_materials(mesh, prepared->gltf, &prepared->textures);
    prepared->textures.path = NULL;
    const wgr_handle_t handle = wgr_handle_pool_alloc(&wgr_mesh_pool);
    if (handle == 0) {
        log_error("mesh: pool full (%u)", (unsigned)wgr_mesh_pool.max - 1u);
        return WGR_LOADER_FAILED;
    }
    if (path != NULL && path[0] != '\0') {
        snprintf(mesh->path, sizeof(mesh->path), "%s", path);
        mesh->has_path = true;
    }
    mesh->ref_count = 1;
    wgr_handle_pool_resolve(&wgr_mesh_pool, handle, &index);
    wgr_meshes[index] = *mesh;
    memset(mesh, 0, sizeof(*mesh));
    *resource = handle;
    return WGR_LOADER_DONE;
}

/* ------------------------------------------------------ generated meshes */

/* A mesh of generated geometry (internal/wgr_mesh_shapes.h), under `key` (its
 * parameters): one primitive in the glTF vertex layout, with generated tangents and
 * picking data, and one material: white, not metallic, roughness 0.5. Takes the
 * shape's arrays. */
static wgr_handle_t create_generated(const char *key, wgr_mesh_shape_t *shape)
{
    const int vcount = shape->vertex_count;
    const size_t stride = 18; /* position 3, normal 3, texcoord0 2, texcoord1 2, tangent 4, color 4 */
    float *tangents = calloc((size_t)vcount * 4, sizeof(float));
    float *verts = calloc((size_t)vcount * stride, sizeof(float));
    wgr_mesh_t mesh = {0};
    wgr_primitive_t *prim;
    wgr_handle_t handle;
    uint16_t index = 0;

    mesh.prims = calloc(1, sizeof(wgr_primitive_t));
    mesh.materials = calloc(1, sizeof(wgr_handle_t));
    if (tangents == NULL || verts == NULL || mesh.prims == NULL || mesh.materials == NULL) {
        log_error("mesh: out of memory");
        free(tangents);
        free(verts);
        free(mesh.prims);
        free(mesh.materials);
        wgr_mesh_shape_free(shape);
        return 0;
    }
    wgr_model_generate_tangents(shape->positions, shape->normals, shape->uvs, vcount, shape->indices,
                               shape->index_count, tangents);
    prim = &mesh.prims[0];
    prim->pmin = (vec3_t){1e30f, 1e30f, 1e30f};
    prim->pmax = (vec3_t){-1e30f, -1e30f, -1e30f};
    for (int i = 0; i < vcount; i++) {
        const float *p = &shape->positions[i * 3];
        float *v = &verts[(size_t)i * stride];
        memcpy(v, p, 3 * sizeof(float));
        memcpy(v + 3, &shape->normals[i * 3], 3 * sizeof(float));
        memcpy(v + 6, &shape->uvs[i * 2], 2 * sizeof(float));
        memcpy(v + 8, &shape->uvs[i * 2], 2 * sizeof(float)); /* both texture coordinate sets */
        memcpy(v + 10, &tangents[i * 4], 4 * sizeof(float));
        v[14] = v[15] = v[16] = v[17] = 1.0f; /* white */
        prim->pmin = (vec3_t){fminf(prim->pmin.x, p[0]), fminf(prim->pmin.y, p[1]), fminf(prim->pmin.z, p[2])};
        prim->pmax = (vec3_t){fmaxf(prim->pmax.x, p[0]), fmaxf(prim->pmax.y, p[1]), fmaxf(prim->pmax.z, p[2])};
    }
    free(tangents);
    prim->upload_vertices = verts;
    prim->upload_bytes = (size_t)vcount * stride * sizeof(float);
    prim->index_count = shape->index_count;
    prim->pick_positions = shape->positions; /* the mesh keeps these for picking */
    prim->pick_indices = shape->indices;
    prim->pick_vertex_count = vcount;
    shape->positions = NULL;
    shape->indices = NULL;
    wgr_mesh_shape_free(shape);
    mesh.prim_count = 1;
    mesh.lmin = prim->pmin;
    mesh.lmax = prim->pmax;
    mesh.material_count = 1;
    mesh.materials[0] = wgr_material_create(WGR_MATERIAL_PBR);
    wgr_material_set_float(mesh.materials[0], "metallic", 0.0f);
    wgr_material_set_float(mesh.materials[0], "roughness", 0.5f);
    snprintf(mesh.path, sizeof(mesh.path), "%s", key);
    mesh.has_path = true;
    mesh.generated = true;
    mesh.ref_count = 1;

    handle = upload_primitive(prim) ? wgr_handle_pool_alloc(&wgr_mesh_pool) : 0;
    if (handle == 0) {
        free_mesh_data(&mesh);
        return 0;
    }
    wgr_handle_pool_resolve(&wgr_mesh_pool, handle, &index);
    wgr_meshes[index] = mesh;
    return handle;
}

