static unsigned char *read_file_bytes(const char *path, int *out_size)
{
    FILE *f;
    long size;
    unsigned char *bytes;

    char found[512];
    *out_size = 0;
    if (path != NULL && wgr_asset_found_path(path, found, sizeof(found))) {
        path = found; /* the asset layer found it elsewhere (a redirect, a fallback) */
    }
    if (path == NULL || (f = fopen(path, "rb")) == NULL) {
        return NULL; /* callers report it */
    }
    fseek(f, 0, SEEK_END); size = ftell(f); fseek(f, 0, SEEK_SET);
    if (size <= 0) { fclose(f); return NULL; }
    bytes = (unsigned char *)malloc((size_t)size);
    if (bytes == NULL) { fclose(f); return NULL; }
    if (fread(bytes, 1, (size_t)size, f) != (size_t)size) { free(bytes); fclose(f); return NULL; }
    fclose(f);
    *out_size = (int)size;
    return bytes;
}

