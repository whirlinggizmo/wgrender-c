vec3_t wgr_model_skin_position(const wgr_mat4_t *joints, int joint_count, vec3_t p,
                              const uint8_t joint_index[4], const float weights[4])
{
    vec3_t out = {0.0f, 0.0f, 0.0f};
    for (int k = 0; k < 4; k++) {
        const float w = weights[k];
        const wgr_mat4_t *m;
        if (w == 0.0f || joint_index[k] >= joint_count) {
            continue;
        }
        m = &joints[joint_index[k]];
        out.x += w * (m->m[0] * p.x + m->m[4] * p.y + m->m[8] * p.z + m->m[12]);
        out.y += w * (m->m[1] * p.x + m->m[5] * p.y + m->m[9] * p.z + m->m[13]);
        out.z += w * (m->m[2] * p.x + m->m[6] * p.y + m->m[10] * p.z + m->m[14]);
    }
    return out;
}

/* A texture coordinate wrapped into 0..1 like the GPU sampler does. */
static float wrap_coord(float c, wgr_texture_wrap_t wrap)
{
    switch (wrap) {
        case WGR_TEXTURE_WRAP_CLAMP:
            return c < 0.0f ? 0.0f : (c > 1.0f ? 1.0f : c);
        case WGR_TEXTURE_WRAP_MIRROR: {
            float t = c - 2.0f * floorf(c * 0.5f); /* 0..2 */
            return t > 1.0f ? 2.0f - t : t;
        }
        default:
            return c - floorf(c);
    }
}

float wgr_model_sample_alpha(const uint8_t *alpha, int width, int height, float u, float v,
                            wgr_texture_wrap_t wrap_u, wgr_texture_wrap_t wrap_v)
{
    int x, y;
    if (alpha == NULL || width <= 0 || height <= 0) {
        return 1.0f;
    }
    u = wrap_coord(u, wrap_u);
    v = wrap_coord(v, wrap_v);
    x = (int)(u * (float)width);
    y = (int)(v * (float)height);
    x = x >= width ? width - 1 : x;
    y = y >= height ? height - 1 : y;
    return (float)alpha[y * width + x] / 255.0f;
}

/* Pose the skinned primitives' pick geometry with the model's current joint
 * matrices, cached until the pose changes. Returns false when the bind pose
 * applies (not animated, or no skin), in which case pick_positions are used. */
static bool update_posed_geometry(wgr_model_t *model_ptr, wgr_mesh_t *mesh_ptr)
{
    int total = 0, offset = 0;
    const int joint_count = mesh_ptr->joint_count < WGR_MAX_JOINTS ? mesh_ptr->joint_count : WGR_MAX_JOINTS;

    if (model_ptr->pose_version == 0 || !mesh_ptr->has_skin) {
        return false;
    }
    if (model_ptr->posed_version == model_ptr->pose_version && model_ptr->posed_mesh == model_ptr->mesh) {
        return true;
    }
    for (int p = 0; p < mesh_ptr->prim_count; p++) {
        if (mesh_ptr->prims[p].skinned) {
            total += mesh_ptr->prims[p].pick_vertex_count;
        }
    }
    if (total > model_ptr->posed_capacity) {
        float *grown = (float *)realloc(model_ptr->posed_positions, (size_t)total * 3 * sizeof(float));
        if (grown == NULL) {
            return false;
        }
        model_ptr->posed_positions = grown;
        model_ptr->posed_capacity = total;
    }

    model_ptr->posed_min = (vec3_t){1e30f, 1e30f, 1e30f};
    model_ptr->posed_max = (vec3_t){-1e30f, -1e30f, -1e30f};
    for (int p = 0; p < mesh_ptr->prim_count; p++) {
        const wgr_primitive_t *prim = &mesh_ptr->prims[p];
        if (!prim->skinned || prim->pick_joints == NULL || prim->pick_weights == NULL) {
            /* static primitive: its bind bounds are its bounds */
            vec3_t lo = prim->pmin, hi = prim->pmax;
            model_ptr->posed_min = (vec3_t){lo.x < model_ptr->posed_min.x ? lo.x : model_ptr->posed_min.x,
                                            lo.y < model_ptr->posed_min.y ? lo.y : model_ptr->posed_min.y,
                                            lo.z < model_ptr->posed_min.z ? lo.z : model_ptr->posed_min.z};
            model_ptr->posed_max = (vec3_t){hi.x > model_ptr->posed_max.x ? hi.x : model_ptr->posed_max.x,
                                            hi.y > model_ptr->posed_max.y ? hi.y : model_ptr->posed_max.y,
                                            hi.z > model_ptr->posed_max.z ? hi.z : model_ptr->posed_max.z};
            continue;
        }
        for (int v = 0; v < prim->pick_vertex_count; v++) {
            vec3_t bind = {prim->pick_positions[v * 3], prim->pick_positions[v * 3 + 1], prim->pick_positions[v * 3 + 2]};
            vec3_t posed = wgr_model_skin_position(model_ptr->joint_matrices, joint_count, bind,
                                                  &prim->pick_joints[v * 4], &prim->pick_weights[v * 4]);
            float *dst = &model_ptr->posed_positions[(offset + v) * 3];
            dst[0] = posed.x; dst[1] = posed.y; dst[2] = posed.z;
            if (posed.x < model_ptr->posed_min.x) model_ptr->posed_min.x = posed.x;
            if (posed.y < model_ptr->posed_min.y) model_ptr->posed_min.y = posed.y;
            if (posed.z < model_ptr->posed_min.z) model_ptr->posed_min.z = posed.z;
            if (posed.x > model_ptr->posed_max.x) model_ptr->posed_max.x = posed.x;
            if (posed.y > model_ptr->posed_max.y) model_ptr->posed_max.y = posed.y;
            if (posed.z > model_ptr->posed_max.z) model_ptr->posed_max.z = posed.z;
        }
        offset += prim->pick_vertex_count;
    }
    model_ptr->posed_version = model_ptr->pose_version;
    model_ptr->posed_mesh = model_ptr->mesh;
    return true;
}

/* The model's transform as a matrix. Built once and kept: a frame asks for it to cull,
 * again to draw, and again for bounds, and building it is four matrix multiplies. */
static wgr_mat4_t model_world(wgr_model_t *model_ptr)
{
    if (model_ptr->world_dirty) {
        model_ptr->world = wgr_mat4_trs(model_ptr->position, model_ptr->rotation, model_ptr->scale);
        model_ptr->world_dirty = false;
    }
    return model_ptr->world;
}

/* Bounds for culling: never re-skins to find them. An animated model's pose changes
 * every frame, so asking for exact posed bounds here would re-skin every vertex of
 * every model, every frame — the rest pose padded by the scene is what culling wants.
 * Posed bounds are used only when a pick has already worked them out for this pose. */
static bool model_cull_bounds(wgr_handle_t handle, vec3_t *lmin, vec3_t *lmax, wgr_mat4_t *model_mat)
{
    wgr_model_t *model_ptr = resolve(handle);
    wgr_mesh_t *mesh_ptr = model_ptr != NULL ? resolve_mesh(model_ptr->mesh) : NULL;

    if (model_ptr == NULL || mesh_ptr == NULL || !model_ptr->visible || mesh_ptr->prim_count == 0) {
        return false;
    }
    if (mesh_ptr->has_skin && model_ptr->pose_version != 0 && model_ptr->posed_version == model_ptr->pose_version &&
        model_ptr->posed_mesh == model_ptr->mesh) {
        *lmin = model_ptr->posed_min;
        *lmax = model_ptr->posed_max;
    } else {
        *lmin = mesh_ptr->lmin;
        *lmax = mesh_ptr->lmax;
    }
    *model_mat = model_world(model_ptr);
    return true;
}

static bool model_bounds(wgr_handle_t handle, vec3_t *lmin, vec3_t *lmax, wgr_mat4_t *model_mat)
{
    wgr_model_t *model_ptr = resolve(handle);
    wgr_mesh_t *mesh_ptr = model_ptr ? resolve_mesh(model_ptr->mesh) : NULL;
    if (model_ptr == NULL || mesh_ptr == NULL || !model_ptr->visible || mesh_ptr->prim_count == 0) {
        return false;
    }
    if (update_posed_geometry(model_ptr, mesh_ptr)) {
        *lmin = model_ptr->posed_min; /* animated: bounds of the current pose */
        *lmax = model_ptr->posed_max;
    } else {
        *lmin = mesh_ptr->lmin;
        *lmax = mesh_ptr->lmax;
    }
    *model_mat = model_world(model_ptr);
    return true;
}

/* The material a model draws a primitive with: the model's override for the
 * primitive's slot, else the mesh's material, else glTF's default material. */
static const wgr_material_t *prim_material(const wgr_model_t *model_ptr, const wgr_mesh_t *mesh_ptr,
                                          const wgr_primitive_t *prim)
{
    static const wgr_material_t fallback = {
        .shading = WGR_MATERIAL_PBR,
        .alpha_cutoff = 0.5f,
        .base_color = {1.0f, 1.0f, 1.0f, 1.0f},
        .metallic = 1.0f,
        .roughness = 1.0f,
        .normal_scale = 1.0f,
        .occlusion_strength = 1.0f,
    };
    const wgr_material_t *material = NULL;

    if (prim->material >= 0 && prim->material < WGR_MAX_MATERIAL_SLOTS) {
        material = wgr_material_get(model_ptr->materials[prim->material]);
    }
    if (material == NULL && prim->material >= 0 && prim->material < mesh_ptr->material_count) {
        material = wgr_material_get(mesh_ptr->materials[prim->material]);
    }
    return material != NULL ? material : &fallback;
}

/* Whether a hit at barycentric (u, v) on triangle (i0, i1, i2) lands on a visible
 * part of the material. Opaque materials always do. MASK uses its cutoff; BLEND
 * counts as solid where the material is at least half opaque. Tint is ignored:
 * fading a model doesn't make it unpickable. */
static bool is_solid_at(const wgr_primitive_t *prim, const wgr_material_t *material, uint32_t i0, uint32_t i1,
                        uint32_t i2, float u, float v)
{
    const wgr_material_texture_t *base = &material->textures[WGR_MATERIAL_TEXTURE_BASE_COLOR];
    const float *uvs = prim->pick_uvs[base->texcoord == 1 ? 1 : 0];
    const float w0 = 1.0f - u - v;
    float alpha = material->base_color[3];
    const unsigned char *mask;
    int width, height;

    if (material->alpha_mode == WGR_ALPHA_OPAQUE || material->shader != 0) {
        return true; /* custom shaders: libwgrender can't know where they're see-through */
    }

    if (prim->pick_alpha != NULL) {
        alpha *= prim->pick_alpha[i0] * w0 + prim->pick_alpha[i1] * u + prim->pick_alpha[i2] * v;
    }
    if (uvs != NULL && wgr_texture_get_alpha_mask(base->texture, &mask, &width, &height)) {
        float m[6];
        const float su = uvs[i0 * 2] * w0 + uvs[i1 * 2] * u + uvs[i2 * 2] * v;
        const float sv = uvs[i0 * 2 + 1] * w0 + uvs[i1 * 2 + 1] * u + uvs[i2 * 2 + 1] * v;
        wgr_material_uv_matrix(base, m);
        alpha *= wgr_model_sample_alpha(mask, width, height, m[0] * su + m[1] * sv + m[2], m[3] * su + m[4] * sv + m[5],
                                       base->wrap_u, base->wrap_v);
    }
    return alpha >= (material->alpha_mode == WGR_ALPHA_MASK ? material->alpha_cutoff : 0.5f);
}

static bool model_pick(wgr_handle_t handle, vec3_t origin, vec3_t dir, wgr_pick_result_t *out)
{
    wgr_model_t *model_ptr = resolve(handle);
    wgr_mesh_t *mesh_ptr = model_ptr ? resolve_mesh(model_ptr->mesh) : NULL;
    wgr_mat4_t model_mat;
    wgr_ray_t world, local;
    wgr_ray_hit_t best = {0};
    vec3_t lmin, lmax;
    bool posed;
    int posed_offset = 0;

    if (out == NULL || model_ptr == NULL || mesh_ptr == NULL || !model_ptr->visible || !model_ptr->pickable ||
        mesh_ptr->prim_count == 0) {
        return false;
    }
    if (!model_bounds(handle, &lmin, &lmax, &model_mat)) {
        return false;
    }
    posed = update_posed_geometry(model_ptr, mesh_ptr);

    world.origin = origin;
    world.dir = dir;
    local = wgr_pick_ray_to_local(model_mat, world);

    /* Narrow phase: ray/triangle against the geometry as drawn: the current pose
     * for animated skinned primitives, skipping see-through parts of MASK/BLEND
     * materials. */
    for (int p = 0; p < mesh_ptr->prim_count; p++) {
        wgr_primitive_t *prim = &mesh_ptr->prims[p];
        const wgr_material_t *material = prim_material(model_ptr, mesh_ptr, prim);
        const float *positions = prim->pick_positions;
        if (posed && prim->skinned && prim->pick_joints != NULL) {
            positions = &model_ptr->posed_positions[posed_offset * 3];
        }
        if (prim->skinned) {
            posed_offset += prim->pick_vertex_count;
        }
        if (positions == NULL || prim->pick_indices == NULL) {
            continue;
        }
        for (int k = 0; k + 2 < prim->index_count; k += 3) {
            uint32_t i0 = prim->pick_indices[k];
            uint32_t i1 = prim->pick_indices[k + 1];
            uint32_t i2 = prim->pick_indices[k + 2];
            vec3_t v0 = {positions[i0 * 3], positions[i0 * 3 + 1], positions[i0 * 3 + 2]};
            vec3_t v1 = {positions[i1 * 3], positions[i1 * 3 + 1], positions[i1 * 3 + 2]};
            vec3_t v2 = {positions[i2 * 3], positions[i2 * 3 + 1], positions[i2 * 3 + 2]};
            wgr_ray_hit_t th = {0};
            if (wgr_pick_ray_triangle(local, v0, v1, v2, &th) && (!best.hit || th.t < best.t) &&
                is_solid_at(prim, material, i0, i1, i2, th.u, th.v)) {
                best = th;
            }
        }
    }

    if (best.hit) {
        wgr_pick_result_from_local(&best, world, model_mat, out);
    } else {
        *out = (wgr_pick_result_t){0};
    }
    return true;
}

/* ---------------------------------------------------------- draw queue ---- */

/* Resolve a model that has something to draw. */
static wgr_mesh_t *lookup_drawable(wgr_handle_t handle, wgr_model_t **model_out)
{
    wgr_model_t *model_ptr = resolve(handle);
    wgr_mesh_t *mesh_ptr = model_ptr ? resolve_mesh(model_ptr->mesh) : NULL;
    if (model_ptr == NULL || mesh_ptr == NULL || !model_ptr->visible || mesh_ptr->prim_count == 0) {
        return NULL;
    }
    *model_out = model_ptr;
    return mesh_ptr;
}

static wgr_colorf_t model_tint(const wgr_model_t *model_ptr)
{
    return wgr_color_unpack(model_ptr->tint);
}

/* A primitive is transparent if its material blends, or if the model's tint
 * makes it translucent (e.g. fading a model out). */
static bool is_blended(wgr_colorf_t tint, const wgr_material_t *material)
{
    return material->alpha_mode == WGR_ALPHA_BLEND || tint.a < 1.0f;
}

static vec3_t prim_center(const wgr_primitive_t *prim)
{
    return (vec3_t){(prim->pmin.x + prim->pmax.x) * 0.5f,
                    (prim->pmin.y + prim->pmax.y) * 0.5f,
                    (prim->pmin.z + prim->pmax.z) * 0.5f};
}

static void log_queue_full(void)
{
    if (!wgr_model_queue_full_logged) {
        log_warn("model: draw queue full (%d placements / %d primitives per frame); "
                 "the rest of this frame's models aren't drawn",
                 MAX_MODEL_DRAWS, MAX_MODEL_ITEMS);
        wgr_model_queue_full_logged = true;
    }
}

/* Room for one more in a queue that doubles up to `max`. The queue is addressed by
 * index everywhere, so growing it doesn't invalidate anything a caller holds. */
static bool reserve_queue(void **items, int *capacity, int count, size_t item_size, int initial, int max)
{
    if (count < *capacity) {
        return true;
    }
    if (*capacity >= max) {
        log_queue_full();
        return false;
    }
    int grown = *capacity > 0 ? *capacity * 2 : initial;
    if (grown > max) {
        grown = max;
    }
    void *moved = realloc(*items, item_size * (size_t)grown);
    if (moved == NULL) {
        log_queue_full(); /* out of memory is the same story to a caller: it won't draw */
        return false;
    }
    *items = moved;
    *capacity = grown;
    return true;
}

/* Capture the model's matrices and tint for this frame. Consecutive submissions
 * of the same model reuse one placement. Returns the placement index or -1. */
static int begin_draw(wgr_handle_t handle, wgr_model_t *model_ptr)
{
    wgr_camera3d_t cam;
    wgr_mat4_t model_mat, view, proj;
    float aspect;
    wgr_model_draw_t *e;
    vec2_t target_size;

    const int light_env = wgr_light_env_current();
    const wgr_light_env_t *env = wgr_light_env_get(light_env);
    wgr_mesh_t *mesh_ptr = resolve_mesh(model_ptr->mesh);

    if (wgr_model_draw_count > 0 && wgr_model_draws[wgr_model_draw_count - 1].model == handle &&
        wgr_model_draws[wgr_model_draw_count - 1].light_env == light_env &&
        wgr_model_draws[wgr_model_draw_count - 1].pass == wgr_render_current_pass()) {
        return wgr_model_draw_count - 1;
    }
    if (!reserve_queue((void **)&wgr_model_draws, &wgr_model_draw_capacity, wgr_model_draw_count,
                       sizeof(*wgr_model_draws), MODEL_DRAWS_INITIAL, MAX_MODEL_DRAWS)) {
        return -1;
    }
    if (!wgr_camera3d_get_active_data(&cam)) {
        return -1;
    }

    target_size = wgr_render_target_size(); /* the screen, or the render target being drawn into */
    aspect = target_size.y > 0.0f ? target_size.x / target_size.y : 1.0f;
    model_mat = model_world(model_ptr);
    view = wgr_camera3d_view(&cam);
    proj = wgr_camera3d_projection(&cam, aspect);

    e = &wgr_model_draws[wgr_model_draw_count];
    e->model = handle;
    e->pass = wgr_render_current_pass();
    e->view_proj = wgr_mat4_mul(proj, view);
    e->mvp = wgr_mat4_mul(e->view_proj, model_mat);
    e->model_mat = model_mat;
    e->model_view = wgr_mat4_mul(view, model_mat);
    e->normal_mat = wgr_mat4_transpose(wgr_mat4_inverse(model_mat));
    e->camera_pos = cam.position;
    e->tint = model_tint(model_ptr);

    /* choose this placement's lights once, from its world bounds */
    e->light_env = env != NULL ? light_env : -1;
    e->joint_base = -1;
    if (mesh_ptr != NULL && mesh_ptr->has_skin && mesh_ptr->joint_count > 0) {
        const int count = mesh_ptr->joint_count;
        if (wgr_model_joint_count + count > wgr_model_joint_capacity) {
            int capacity = wgr_model_joint_capacity > 0 ? wgr_model_joint_capacity * 2 : 256;
            while (capacity < wgr_model_joint_count + count) capacity *= 2;
            float *grown = realloc(wgr_model_joints, sizeof(float) * 16 * (size_t)capacity);
            if (grown != NULL) {
                wgr_model_joints = grown;
                wgr_model_joint_capacity = capacity;
            }
        }
        if (wgr_model_joint_count + count <= wgr_model_joint_capacity) {
            e->joint_base = wgr_model_joint_count;
            for (int j = 0; j < count; j++) {
                memcpy(&wgr_model_joints[(size_t)(wgr_model_joint_count + j) * 16], model_ptr->joint_matrices[j].m,
                       16 * sizeof(float));
            }
            wgr_model_joint_count += count;
        } else if (!wgr_model_joints_overflow_logged) {
            log_error("model: out of memory for the frame's joint matrices");
            wgr_model_joints_overflow_logged = true;
        }
    }
    e->light_count = 0;
    e->has_bounds = mesh_ptr != NULL;
    if (e->has_bounds) {
        wgr_pick_world_aabb(mesh_ptr->lmin, mesh_ptr->lmax, model_mat, &e->wmin, &e->wmax);
        wgr_aabb_pad(&e->wmin, &e->wmax, WGR_CULL_PAD); /* the rest pose isn't the whole animation */
    }
    if (env != NULL && e->has_bounds) {
        e->light_count = wgr_light_select(env, e->wmin, e->wmax, e->lights, WGR_MAX_DRAW_LIGHTS);
    }
    return wgr_model_draw_count++;
}

static bool push_item(int draw, int prim, bool blended)
{
    if (!reserve_queue((void **)&wgr_model_items, &wgr_model_item_capacity, wgr_model_item_count,
                       sizeof(*wgr_model_items), MODEL_ITEMS_INITIAL, MAX_MODEL_ITEMS)) {
        return false;
    }
    wgr_model_items[wgr_model_item_count++] = (wgr_model_item_t){
        .draw = draw,
        .prim = prim,
        .region = blended ? -1 : wgr_model_region, /* see-through parts keep their order */
        .blended = blended,
    };
    return true;
}

/* Farthest first. */
static int compare_blend_prims(const void *a, const void *b)
{
    float da = ((const wgr_blend_prim_t *)a)->depth;
    float db = ((const wgr_blend_prim_t *)b)->depth;
    return (da < db) - (da > db);
}

/* wgr_model_draw(): opaque primitives, then this model's transparent primitives
 * back to front. Not sorted against other drawables (use a scene for that). */
static void draw_immediate(wgr_handle_t handle)
{
    wgr_model_t *model_ptr = NULL;
    wgr_mesh_t *mesh_ptr = lookup_drawable(handle, &model_ptr);
    int draw, first, blend_count = 0;

    if (mesh_ptr == NULL || (draw = begin_draw(handle, model_ptr)) < 0) {
        return;
    }
    first = wgr_model_item_count;
    for (int p = 0; p < mesh_ptr->prim_count; p++) {
        wgr_primitive_t *prim = &mesh_ptr->prims[p];
        if (!is_blended(wgr_model_draws[draw].tint, prim_material(model_ptr, mesh_ptr, prim))) {
            push_item(draw, p, false);
        } else if (blend_count < MAX_BLEND_PRIMS) {
            wgr_blend_prims[blend_count++] = (wgr_blend_prim_t){
                .prim = p,
                .depth = -wgr_mat4_mul_point(wgr_model_draws[draw].model_view, prim_center(prim)).z,
            };
        }
    }
    qsort(wgr_blend_prims, (size_t)blend_count, sizeof(wgr_blend_prims[0]), compare_blend_prims);
    for (int b = 0; b < blend_count; b++) {
        push_item(draw, wgr_blend_prims[b].prim, true);
    }
    wgr_render_submit_models(first, wgr_model_item_count - first);
}

/* Scene opaque pass. */
static void draw_opaque(wgr_handle_t handle)
{
    wgr_model_t *model_ptr = NULL;
    wgr_mesh_t *mesh_ptr = lookup_drawable(handle, &model_ptr);
    wgr_colorf_t tint;
    int draw = -1, first = wgr_model_item_count;

    if (mesh_ptr == NULL) {
        return;
    }
    tint = model_tint(model_ptr);
    for (int p = 0; p < mesh_ptr->prim_count; p++) {
        if (is_blended(tint, prim_material(model_ptr, mesh_ptr, &mesh_ptr->prims[p]))) {
            continue;
        }
        if (draw < 0 && (draw = begin_draw(handle, model_ptr)) < 0) {
            return;
        }
        push_item(draw, p, false);
    }
    wgr_render_submit_models(first, wgr_model_item_count - first);
}

/* Scene transparent pass: one item per transparent primitive. */
static int collect_transparent(wgr_handle_t handle, const wgr_camera3d_t *cam,
                               wgr_transparent_item_t *out, int max_items)
{
    wgr_model_t *model_ptr = NULL;
    wgr_mesh_t *mesh_ptr = lookup_drawable(handle, &model_ptr);
    wgr_colorf_t tint;
    wgr_mat4_t model_mat;
    int count = 0;

    if (mesh_ptr == NULL) {
        return 0;
    }
    tint = model_tint(model_ptr);
    model_mat = model_world(model_ptr);
    for (int p = 0; p < mesh_ptr->prim_count && count < max_items; p++) {
        const wgr_primitive_t *prim = &mesh_ptr->prims[p];
        if (!is_blended(tint, prim_material(model_ptr, mesh_ptr, prim))) {
            continue;
        }
        out[count++] = (wgr_transparent_item_t){
            .handle = handle,
            .part = p,
            .depth = wgr_scene_view_depth(cam, wgr_mat4_mul_point(model_mat, prim_center(prim))),
        };
    }
    return count;
}

static void draw_transparent(wgr_handle_t handle, int part)
{
    wgr_model_t *model_ptr = NULL;
    wgr_mesh_t *mesh_ptr = lookup_drawable(handle, &model_ptr);
    int draw, first = wgr_model_item_count;

    if (mesh_ptr == NULL || part < 0 || part >= mesh_ptr->prim_count ||
        (draw = begin_draw(handle, model_ptr)) < 0) {
        return;
    }
    if (push_item(draw, part, true)) {
        wgr_render_submit_models(first, 1);
    }
}

/* The scene and light blocks applied last, and whether they still hold: sokol needs
 * every block applied again after a pipeline change (reset_fs_blocks). */
static fs_scene_t last_scene;
static fs_lights_t last_lights;
static bool scene_applied, lights_applied;

static void reset_fs_blocks(void)
{
    scene_applied = lights_applied = false;
}

/* The material (every draw), and the scene and its lights (only when they change:
 * they're the same for most draws in a frame). */
static void apply_fs(const wgr_model_draw_t *e, const wgr_material_t *material, const wgr_environment_binding_t *binding,
                     const wgr_shadow_binding_t *shadow, bool receives_shadow)
{
    fs_params_t fsp;
    fs_scene_t scene;
    fs_lights_t lights;
    const wgr_light_env_t *env = wgr_light_env_get(e->light_env);
    const bool lit = env != NULL && material->shading == WGR_MATERIAL_PBR;

    memset(&fsp, 0, sizeof(fsp));
    memset(&scene, 0, sizeof(scene));
    memset(&lights, 0, sizeof(lights));
    /* the placement's tint isn't here: it rides the vertex color, out of the instance
       record, so this block holds nothing that changes from placement to placement */
    fsp.u_base_color[0] = material->base_color[0];
    fsp.u_base_color[1] = material->base_color[1];
    fsp.u_base_color[2] = material->base_color[2];
    fsp.u_base_color[3] = material->base_color[3];
    fsp.u_emissive[0] = material->emissive[0];
    fsp.u_emissive[1] = material->emissive[1];
    fsp.u_emissive[2] = material->emissive[2];
    /* without a normal map the flat default texture must not tilt the normal */
    fsp.u_emissive[3] = material->textures[WGR_MATERIAL_TEXTURE_NORMAL].texture != 0 ? material->normal_scale : 0.0f;
    fsp.u_pbr[0] = material->metallic;
    fsp.u_pbr[1] = material->roughness;
    fsp.u_pbr[2] = material->occlusion_strength;
    fsp.u_pbr[3] = lit ? 1.0f : 0.0f;
    fsp.u_material[0] = material->alpha_mode == WGR_ALPHA_MASK ? material->alpha_cutoff : 0.0f;
    fsp.u_material[2] = lit && receives_shadow ? 1.0f : 0.0f;
    for (int t = 0; t < WGR_MATERIAL_TEXTURE_COUNT; t++) {
        float m[6];
        wgr_material_uv_matrix(&material->textures[t], m);
        if (wgr_texture_is_flipped(material->textures[t].texture)) { /* render target stored bottom-up */
            m[3] = -m[3];
            m[4] = -m[4];
            m[5] = 1.0f - m[5];
        }
        fsp.u_uv_row0[t][0] = m[0];
        fsp.u_uv_row0[t][1] = m[1];
        fsp.u_uv_row0[t][2] = m[2];
        fsp.u_uv_row0[t][3] = (float)material->textures[t].texcoord;
        fsp.u_uv_row1[t][0] = m[3];
        fsp.u_uv_row1[t][1] = m[4];
        fsp.u_uv_row1[t][2] = m[5];
    }

    scene.u_camera_pos[0] = e->camera_pos.x;
    scene.u_camera_pos[1] = e->camera_pos.y;
    scene.u_camera_pos[2] = e->camera_pos.z;
    /* exposure and tone mapping come from the scene; models outside a scene show raw colors */
    scene.u_tonemap[0] = env != NULL ? (float)env->tonemap : 0.0f;
    scene.u_tonemap[1] = env != NULL ? powf(2.0f, env->exposure) : 1.0f;
    if (lit && receives_shadow) { /* the frame's casting lights, a layer each */
        wgr_shadow_fill_uniforms(shadow, scene.u_shadow_mat, scene.u_shadow_params, scene.u_shadow_tint,
                                scene.u_shadow_extra, scene.u_shadow_map);
    }
    if (lit && binding->valid && env->environment_intensity > 0.0f) {
        scene.u_env[0] = env->environment_intensity;
        scene.u_env[1] = binding->max_lod;
        scene.u_env[2] = cosf(env->environment_rotation);
        scene.u_env[3] = sinf(env->environment_rotation);
        for (int k = 0; k < 9; k++) {
            scene.u_sh[k][0] = binding->sh.c[k][0];
            scene.u_sh[k][1] = binding->sh.c[k][1];
            scene.u_sh[k][2] = binding->sh.c[k][2];
        }
    }
    if (lit) {
        scene.u_ambient[0] = env->ambient.x;
        scene.u_ambient[1] = env->ambient.y;
        scene.u_ambient[2] = env->ambient.z;
        fsp.u_material[1] = (float)e->light_count;
        for (int i = 0; i < e->light_count; i++) {
            const wgr_scene_light_t *light = &env->lights[e->lights[i]];
            lights.u_light_pos_range[i][0] = light->position.x;
            lights.u_light_pos_range[i][1] = light->position.y;
            lights.u_light_pos_range[i][2] = light->position.z;
            lights.u_light_pos_range[i][3] = light->range;
            lights.u_light_dir_type[i][0] = light->direction.x;
            lights.u_light_dir_type[i][1] = light->direction.y;
            lights.u_light_dir_type[i][2] = light->direction.z;
            lights.u_light_dir_type[i][3] = (float)light->type;
            lights.u_light_radiance[i][0] = light->radiance.x;
            lights.u_light_radiance[i][1] = light->radiance.y;
            lights.u_light_radiance[i][2] = light->radiance.z;
            lights.u_light_spot[i][0] = light->cos_inner;
            lights.u_light_spot[i][1] = light->cos_outer;
            lights.u_light_spot[i][2] =
                (float)(lit && receives_shadow ? wgr_shadow_slot_of(shadow, e->lights[i]) : -1);
        }
    }
    sg_apply_uniforms(UB_fs_params, &(sg_range){.ptr = &fsp, .size = sizeof(fsp)});
    if (!scene_applied || memcmp(&scene, &last_scene, sizeof(scene)) != 0) {
        sg_apply_uniforms(UB_fs_scene, &(sg_range){.ptr = &scene, .size = sizeof(scene)});
        last_scene = scene;
        scene_applied = true;
    }
    if (!lights_applied || memcmp(&lights, &last_lights, sizeof(lights)) != 0) {
        sg_apply_uniforms(UB_fs_lights, &(sg_range){.ptr = &lights, .size = sizeof(lights)});
        last_lights = lights;
        lights_applied = true;
    }
}

static sg_view texture_view(const wgr_material_texture_t *texture, sg_view fallback)
{
    sg_view view = fallback;
    if (texture->texture != 0) {
        wgr_texture_get_binding(texture->texture, &view, NULL, NULL, NULL);
    }
    return view;
}

static sg_sampler texture_sampler(const wgr_material_texture_t *texture)
{
    return wgr_texture_sampler(texture->wrap_u, texture->wrap_v, texture->filter, texture->mipmaps);
}

/* Uniform blocks of custom shaders (shaders/wgr.glsl), std140; wgr_frame is
 * wgr_shader_frame_t (internal/wgr_shader.h). */
typedef struct {
    float view_proj[16], time_base[4]; /* x seconds, y this draw's first instance record */
} custom_object_t;

/* A primitive whose material has a custom shader (wgr_shader.h). */
static void draw_custom(const wgr_model_draw_t *e, const wgr_model_t *model_ptr, const wgr_primitive_t *prim,
                        const wgr_material_t *material, bool blended, sg_pipeline *cur_pip, int instance_base,
                        int instances)
{
    wgr_shader_t *shader = wgr_shader_hooks.get != NULL ? wgr_shader_hooks.get(material->shader) : NULL;
    const int s = prim->skinned ? 1 : 0, b = blended ? 1 : 0, d = material->double_sided ? 1 : 0;
    const wgr_shader_program_t *program;
    const wgr_light_env_t *env = wgr_light_env_get(e->light_env);
    const float time = (float)wgr_get_time();
    sg_bindings bind = {.vertex_buffers[0] = prim->vbuf, .index_buffer = prim->ibuf};
    wgr_environment_binding_t environment;
    wgr_shadow_binding_t shadow = {0};
    wgr_environment_get_binding(env != NULL ? env->environment : 0, &environment);
    if (wgr_shadow_hooks.get_binding != NULL) {
        wgr_shadow_hooks.get_binding(e->light_env, &shadow);
    }

    if (shader == NULL) return; /* released while the material was queued */
    program = &shader->programs[s];
    if (shader->pipelines[s][b][d].id == SG_INVALID_ID) {
        shader->pipelines[s][b][d] = make_pipeline(program->shader, prim->skinned, blended, material->double_sided);
    }
    if (shader->pipelines[s][b][d].id != cur_pip->id) {
        sg_apply_pipeline(shader->pipelines[s][b][d]);
        *cur_pip = shader->pipelines[s][b][d];
    }

    {   /* the camera, and where this draw's placements start; the rest is per record */
        custom_object_t object = {.time_base = {time, (float)instance_base}};
        memcpy(object.view_proj, e->view_proj.m, sizeof(object.view_proj));
        sg_apply_uniforms(WGR_SHADER_BLOCK_OBJECT, &(sg_range){.ptr = &object, .size = sizeof(object)});
    }

    if (program->has_block[WGR_SHADER_BLOCK_FRAME]) {
        wgr_shader_frame_t frame;
        memset(&frame, 0, sizeof(frame));
        frame.camera_time[0] = e->camera_pos.x;
        frame.camera_time[1] = e->camera_pos.y;
        frame.camera_time[2] = e->camera_pos.z;
        frame.camera_time[3] = time;
        /* the tint isn't here: it comes per placement, out of the instance record */
        frame.output[0] = material->alpha_mode == WGR_ALPHA_MASK ? material->alpha_cutoff : 0.0f;
        frame.output[1] = env != NULL ? (float)env->tonemap : 0.0f;
        frame.output[2] = env != NULL ? powf(2.0f, env->exposure) : 1.0f;
        if (env != NULL) {
            frame.ambient_count[0] = env->ambient.x;
            frame.ambient_count[1] = env->ambient.y;
            frame.ambient_count[2] = env->ambient.z;
            frame.ambient_count[3] = (float)e->light_count;
            for (int i = 0; i < e->light_count; i++) {
                const wgr_scene_light_t *light = &env->lights[e->lights[i]];
                frame.light_pos_range[i][0] = light->position.x;
                frame.light_pos_range[i][1] = light->position.y;
                frame.light_pos_range[i][2] = light->position.z;
                frame.light_pos_range[i][3] = light->range;
                frame.light_dir_type[i][0] = light->direction.x;
                frame.light_dir_type[i][1] = light->direction.y;
                frame.light_dir_type[i][2] = light->direction.z;
                frame.light_dir_type[i][3] = (float)light->type;
                frame.light_radiance[i][0] = light->radiance.x;
                frame.light_radiance[i][1] = light->radiance.y;
                frame.light_radiance[i][2] = light->radiance.z;
                frame.light_spot[i][0] = light->cos_inner;
                frame.light_spot[i][1] = light->cos_outer;
                frame.light_spot[i][2] =
                    (float)(model_ptr->receives_shadow ? wgr_shadow_slot_of(&shadow, e->lights[i]) : -1);
            }
            if (environment.valid && env->environment_intensity > 0.0f) {
                frame.env[0] = env->environment_intensity;
                frame.env[1] = environment.max_lod;
                frame.env[2] = cosf(env->environment_rotation);
                frame.env[3] = sinf(env->environment_rotation);
                for (int k = 0; k < 9; k++) {
                    frame.sh[k][0] = environment.sh.c[k][0];
                    frame.sh[k][1] = environment.sh.c[k][1];
                    frame.sh[k][2] = environment.sh.c[k][2];
                }
            }
        }
        /* the frame's casting lights, as the built-in shading gets them */
        if (model_ptr->receives_shadow) {
            wgr_shadow_fill_uniforms(&shadow, frame.shadow_mat, frame.shadow_params, frame.shadow_tint,
                                    frame.shadow_extra, frame.shadow_map);
        }
        sg_apply_uniforms(WGR_SHADER_BLOCK_FRAME, &(sg_range){.ptr = &frame, .size = sizeof(frame)});
    }
    if (program->has_block[WGR_SHADER_BLOCK_FS_PARAMS]) {
        sg_apply_uniforms(WGR_SHADER_BLOCK_FS_PARAMS,
                          &(sg_range){.ptr = material->custom_params,
                                      .size = (size_t)shader->block_size[WGR_SHADER_BLOCK_FS_PARAMS]});
    }
    if (program->has_block[WGR_SHADER_BLOCK_VS_PARAMS]) {
        sg_apply_uniforms(WGR_SHADER_BLOCK_VS_PARAMS,
                          &(sg_range){.ptr = material->custom_params + shader->block_size[WGR_SHADER_BLOCK_FS_PARAMS],
                                      .size = (size_t)shader->block_size[WGR_SHADER_BLOCK_VS_PARAMS]});
    }

    for (int t = 0; t < shader->texture_count; t++) {
        if (program->view_slot[t] >= 0) {
            bind.views[program->view_slot[t]] = texture_view(&material->textures[t], wgr_model_white_view);
        }
        if (program->sampler_slot[t] >= 0) {
            bind.samplers[program->sampler_slot[t]] = texture_sampler(&material->textures[t]);
        }
    }
    /* the environment (a black cube without one: wgr_frame's intensity is 0 then) */
    if (program->shadow_view_slot >= 0) {
        bind.views[program->shadow_view_slot] = shadow.valid ? shadow.map : wgr_model_shadow_fallback_view;
    }
    if (program->shadow_sampler_slot >= 0) {
        bind.samplers[program->shadow_sampler_slot] = shadow.valid ? shadow.sampler : wgr_model_shadow_fallback_sampler;
    }
    if (program->env_view_slot >= 0) bind.views[program->env_view_slot] = environment.cube;
    if (program->env_sampler_slot >= 0) bind.samplers[program->env_sampler_slot] = environment.cube_sampler;
    if (program->brdf_view_slot >= 0) bind.views[program->brdf_view_slot] = environment.brdf_lut;
    /* the BRDF table shares the environment's sampler unless it has one of its own */
    if (program->brdf_sampler_slot >= 0 && program->brdf_sampler_slot != program->env_sampler_slot) {
        bind.samplers[program->brdf_sampler_slot] = environment.lut_sampler;
    }
    if (program->joint_view_slot >= 0) { /* skinned: the frame's joint matrices */
        bind.views[program->joint_view_slot] = wgr_model_joint_view;
        if (program->joint_sampler_slot >= 0) bind.samplers[program->joint_sampler_slot] = wgr_model_joint_sampler;
    }
    if (program->instance_view_slot >= 0) { /* where each placement of this draw stands */
        bind.views[program->instance_view_slot] = wgr_model_instance_view;
        if (program->instance_sampler_slot >= 0) {
            bind.samplers[program->instance_sampler_slot] = wgr_model_instance_sampler;
        }
    }
    if (program->sprite_view_slot >= 0) { /* wgr_sprite_color(): white on models, so it's the vertex color */
        sg_view white, black_cube;
        sg_sampler linear;
        wgr_shader_hooks.fallbacks(&white, &black_cube, &linear);
        bind.views[program->sprite_view_slot] = white;
        if (program->sprite_sampler_slot >= 0) bind.samplers[program->sprite_sampler_slot] = linear;
    }
    sg_apply_bindings(&bind);
    sg_draw(0, prim->index_count, instances);
}

/* What an item must agree on to share a draw with the one before it: everything the
 * draw sets outside the instance record. Resolved once here, compared exactly at draw
 * time and hashed for the sort. A material with a custom shader never groups: that path
 * has its own uniforms per placement. */
typedef struct {
    const void *material; /* resolved material, or NULL when the item can't be drawn */
    unsigned vbuf, ibuf;
    int pass, light_env, light_count, lights[WGR_MAX_DRAW_LIGHTS];
    bool skinned, blended, double_sided, receives_shadow, custom;
    const wgr_mat4_t *view_proj;
    vec3_t camera_pos;
} group_key_t;

static bool item_key(const wgr_model_item_t *item, group_key_t *key)
{
    const wgr_model_draw_t *e = &wgr_model_draws[item->draw];
    wgr_model_t *model_ptr = resolve(e->model);
    wgr_mesh_t *mesh_ptr = model_ptr != NULL ? resolve_mesh(model_ptr->mesh) : NULL;
    if (mesh_ptr == NULL || item->prim >= mesh_ptr->prim_count) {
        memset(key, 0, sizeof(*key));
        return false;
    }
    const wgr_primitive_t *prim = &mesh_ptr->prims[item->prim];
    const wgr_material_t *material = prim_material(model_ptr, mesh_ptr, prim);
    memset(key, 0, sizeof(*key));
    key->material = material;
    key->vbuf = prim->vbuf.id;
    key->ibuf = prim->ibuf.id;
    key->pass = e->pass;
    key->light_env = e->light_env;
    key->light_count = e->light_count;
    for (int i = 0; i < e->light_count && i < WGR_MAX_DRAW_LIGHTS; i++) {
        key->lights[i] = e->lights[i];
    }
    key->skinned = prim->skinned;
    key->blended = item->blended;
    key->double_sided = material->double_sided;
    key->receives_shadow = model_ptr->receives_shadow;
    key->custom = material->shader != 0;
    key->view_proj = &e->view_proj;
    key->camera_pos = e->camera_pos;
    return true;
}

/* Whether two items can go up as one draw. */
static bool same_group(const group_key_t *a, const group_key_t *b)
{
    if (a->material == NULL || a->material != b->material) {
        return false;
    }
    if (a->vbuf != b->vbuf || a->ibuf != b->ibuf || a->pass != b->pass || a->light_env != b->light_env ||
        a->skinned != b->skinned || a->blended != b->blended || a->double_sided != b->double_sided ||
        a->receives_shadow != b->receives_shadow || a->light_count != b->light_count) {
        return false;
    }
    for (int i = 0; i < a->light_count; i++) {
        if (a->lights[i] != b->lights[i]) {
            return false;
        }
    }
    /* the camera is per placement, and a program may change it inside a pass */
    return memcmp(&a->camera_pos, &b->camera_pos, sizeof(a->camera_pos)) == 0 &&
           memcmp(a->view_proj->m, b->view_proj->m, sizeof(a->view_proj->m)) == 0;
}

/* A hash of everything same_group() compares, so sorting by it brings groupable items
 * together. A collision only splits a group, it never merges two that differ. */
static unsigned long long key_hash(const group_key_t *k, int item)
{
    unsigned long long h = 1469598103934665603ULL;
    const unsigned char *bytes;
    size_t size;
    if (k->material == NULL) {
        return (unsigned long long)item; /* nothing to draw: keep it where the sort found it */
    }
    for (bytes = (const unsigned char *)&k->material, size = 0; size < sizeof(k->material); size++) {
        h = (h ^ bytes[size]) * 1099511628211ULL;
    }
    unsigned rest[6 + WGR_MAX_DRAW_LIGHTS] = {k->vbuf,      k->ibuf,
                                             (unsigned)k->pass, (unsigned)k->light_env,
                                             (unsigned)k->light_count,
                                             (unsigned)((k->skinned ? 1 : 0) | (k->blended ? 2 : 0) |
                                                        (k->double_sided ? 4 : 0) |
                                                        (k->receives_shadow ? 8 : 0))};
    for (int i = 0; i < k->light_count && i < WGR_MAX_DRAW_LIGHTS; i++) {
        rest[6 + i] = (unsigned)k->lights[i];
    }
    bytes = (const unsigned char *)rest;
    for (size = 0; size < sizeof(rest); size++) {
        h = (h ^ bytes[size]) * 1099511628211ULL;
    }
    return h;
}

typedef struct {
    unsigned long long hash;
    int item;
} sort_entry_t;

static int compare_entries(const void *a, const void *b)
{
    const sort_entry_t *x = (const sort_entry_t *)a, *y = (const sort_entry_t *)b;
    if (x->hash != y->hash) {
        return x->hash < y->hash ? -1 : 1;
    }
    return x->item < y->item ? -1 : (x->item > y->item ? 1 : 0); /* stable */
}

static sort_entry_t *wgr_model_sort_entries;
static wgr_model_item_t *wgr_model_sorted;
static int wgr_model_sort_capacity;

/* Bring equal items together inside each unordered region, so a run of them can go up
 * as one instanced draw. Items outside a region (see-through parts, anything drawn
 * without a scene) keep the order they were submitted in. */
static void sort_items(void)
{
    int start = 0;
    if (wgr_model_item_count > wgr_model_sort_capacity) {
        sort_entry_t *entries = realloc(wgr_model_sort_entries, sizeof(*entries) * (size_t)wgr_model_item_count);
        wgr_model_item_t *sorted = realloc(wgr_model_sorted, sizeof(*sorted) * (size_t)wgr_model_item_count);
        if (entries != NULL) wgr_model_sort_entries = entries;
        if (sorted != NULL) wgr_model_sorted = sorted;
        if (entries == NULL || sorted == NULL) {
            return; /* out of memory: draw them in the order they came in */
        }
        wgr_model_sort_capacity = wgr_model_item_count;
    }
    while (start < wgr_model_item_count) {
        const int region = wgr_model_items[start].region;
        const int pass = wgr_model_draws[wgr_model_items[start].draw].pass;
        int end = start + 1;
        /* a region never spans passes, but the commands that replay this range are per
           pass, so an item must not cross one even if it ever did */
        while (end < wgr_model_item_count && wgr_model_items[end].region == region &&
               wgr_model_draws[wgr_model_items[end].draw].pass == pass) {
            end++;
        }
        if (region >= 0 && end - start > 1) {
            for (int i = start; i < end; i++) {
                group_key_t key;
                item_key(&wgr_model_items[i], &key);
                wgr_model_sort_entries[i - start] = (sort_entry_t){.hash = key_hash(&key, i), .item = i};
            }
            qsort(wgr_model_sort_entries, (size_t)(end - start), sizeof(*wgr_model_sort_entries), compare_entries);
            for (int i = 0; i < end - start; i++) {
                wgr_model_sorted[i] = wgr_model_items[wgr_model_sort_entries[i].item];
            }
            memcpy(&wgr_model_items[start], wgr_model_sorted, sizeof(*wgr_model_items) * (size_t)(end - start));
        }
        start = end;
    }
}

static void draw_primitive(const wgr_model_draw_t *e, const wgr_model_t *model_ptr, const wgr_mesh_t *mesh_ptr,
                           const wgr_primitive_t *prim, bool blended, sg_pipeline *cur_pip, int instance_base,
                           int instances)
{
    const wgr_material_t *material = prim_material(model_ptr, mesh_ptr, prim);
    if (material->shader != 0) {
        draw_custom(e, model_ptr, prim, material, blended, cur_pip, instance_base, instances);
        return;
    }
    const wgr_material_texture_t *textures = material->textures;
    const wgr_light_env_t *light_env = wgr_light_env_get(e->light_env);
    wgr_environment_binding_t environment;
    wgr_shadow_binding_t shadow = {0};
    wgr_environment_get_binding(light_env != NULL ? light_env->environment : 0, &environment);
    if (wgr_shadow_hooks.get_binding != NULL) {
        wgr_shadow_hooks.get_binding(e->light_env, &shadow);
    }
    ensure_pipelines();
    sg_pipeline pip = wgr_pips[prim->skinned ? 1 : 0][blended ? 1 : 0][material->double_sided ? 1 : 0];
    if (pip.id != cur_pip->id) {
        sg_apply_pipeline(pip);
        *cur_pip = pip;
        reset_fs_blocks(); /* a new pipeline needs its uniforms again */
    }

    {   /* the camera, and where this draw's placements start in the instance texture */
        vs_params_t vsp;
        memcpy(vsp.view_proj, e->view_proj.m, sizeof(vsp.view_proj));
        vsp.instance_base[0] = (float)instance_base;
        vsp.instance_base[1] = vsp.instance_base[2] = vsp.instance_base[3] = 0.0f;
        sg_apply_uniforms(prim->skinned ? UB_vs_skin_params : UB_vs_params,
                          &(sg_range){.ptr = &vsp, .size = sizeof(vsp)});
    }

    sg_apply_bindings(&(sg_bindings){
        .vertex_buffers[0] = prim->vbuf,
        .index_buffer = prim->ibuf,
        .views[VIEW_base_color_tex] = texture_view(&textures[WGR_MATERIAL_TEXTURE_BASE_COLOR], wgr_model_white_view),
        .views[VIEW_metallic_roughness_tex] =
            texture_view(&textures[WGR_MATERIAL_TEXTURE_METALLIC_ROUGHNESS], wgr_model_white_view),
        .views[VIEW_normal_tex] = texture_view(&textures[WGR_MATERIAL_TEXTURE_NORMAL], wgr_model_flat_normal_view),
        .views[VIEW_occlusion_tex] = texture_view(&textures[WGR_MATERIAL_TEXTURE_OCCLUSION], wgr_model_white_view),
        .views[VIEW_emissive_tex] = texture_view(&textures[WGR_MATERIAL_TEXTURE_EMISSIVE], wgr_model_white_view),
        .samplers[SMP_base_color_smp] = texture_sampler(&textures[WGR_MATERIAL_TEXTURE_BASE_COLOR]),
        .samplers[SMP_metallic_roughness_smp] = texture_sampler(&textures[WGR_MATERIAL_TEXTURE_METALLIC_ROUGHNESS]),
        .samplers[SMP_normal_smp] = texture_sampler(&textures[WGR_MATERIAL_TEXTURE_NORMAL]),
        .samplers[SMP_occlusion_smp] = texture_sampler(&textures[WGR_MATERIAL_TEXTURE_OCCLUSION]),
        .samplers[SMP_emissive_smp] = texture_sampler(&textures[WGR_MATERIAL_TEXTURE_EMISSIVE]),
        .views[VIEW_joint_tex] = wgr_model_joint_view,
        .samplers[SMP_joint_smp] = wgr_model_joint_sampler,
        .views[VIEW_instance_tex] = wgr_model_instance_view,
        .samplers[SMP_instance_smp] = wgr_model_instance_sampler,
        .views[VIEW_env_tex] = environment.cube,
        .views[VIEW_brdf_tex] = environment.brdf_lut,
        .samplers[SMP_env_smp] = environment.cube_sampler,
        .samplers[SMP_brdf_smp] = environment.lut_sampler,
        .views[VIEW_shadow_tex] = shadow.valid ? shadow.map : wgr_model_shadow_fallback_view,
        .samplers[SMP_shadow_smp] = shadow.valid ? shadow.sampler : wgr_model_shadow_fallback_sampler,
    });
    apply_fs(e, material, &environment, &shadow, model_ptr->receives_shadow);
    sg_draw(0, prim->index_count, instances);
}

